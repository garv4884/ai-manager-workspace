using System.Collections;
using UnityEngine;

namespace AIManagerWorkspace
{
    public class AITaskGenerator : MonoBehaviour
    {
        [SerializeField] private AIServiceManager aiService;
        [SerializeField] private AgentManager agentManager;
        [SerializeField] private float autoTaskInterval = 15f;
        [SerializeField] private bool autoGenerateDemoTasks = true;

        private static readonly string[] demoTasks = new string[]
        {
            "Write a Python function to parse JSON",
            "Design a database schema for user profiles",
            "Research best practices for VR UI design",
            "Review and suggest improvements to this code",
            "Create unit tests for the payment module",
            "Draft a technical specification document"
        };

        private void Start()
        {
            if (aiService != null)
            {
                aiService.OnResponseReceived += OnAIResponseReceived;
            }

            if (autoGenerateDemoTasks)
            {
                InvokeRepeating(nameof(AssignRandomDemoTask), 3f, autoTaskInterval);
            }
        }

        private void OnDestroy()
        {
            if (aiService != null)
            {
                aiService.OnResponseReceived -= OnAIResponseReceived;
            }
        }

        public void AssignRandomDemoTask()
        {
            AgentController freeAgent = agentManager?.GetFreeAgent();
            if (freeAgent == null)
            {
                Debug.Log("[AITaskGenerator] No free agent available for demo task.");
                return;
            }

            string description = demoTasks[Random.Range(0, demoTasks.Length)];
            TaskType type = (Random.value > 0.5f) ? TaskType.NeedsApproval : TaskType.NeedsTextInput;

            TaskData task = CreateTask(description, description, type);
            freeAgent.AssignTask(task);

            Debug.Log($"[AITaskGenerator] Assigned demo task '{description}' (type: {type}) to agent {freeAgent.name}");
        }

        public void AssignTaskToFreeAgent(string description, TaskType type)
        {
            AgentController freeAgent = agentManager?.GetFreeAgent();
            if (freeAgent == null)
            {
                Debug.LogWarning("[AITaskGenerator] No free agent available for task assignment.");
                return;
            }

            TaskData task = CreateTask(description, description, type);
            freeAgent.AssignTask(task);

            Debug.Log($"[AITaskGenerator] Assigned task '{description}' (type: {type}) to agent {freeAgent.name}");
        }

        private void OnAIResponseReceived(string agentId, string response)
        {
            AgentController agent = agentManager?.GetAgentById(agentId);
            if (agent == null)
            {
                Debug.LogWarning($"[AITaskGenerator] No agent found with id '{agentId}'.");
                return;
            }

            if (agent.CurrentTask != null)
            {
                agent.CurrentTask.outputResult = response;
                Debug.Log($"[AITaskGenerator] Updated task output for agent {agentId}.");
            }

            // If agent is in a waiting state, re-enter presentation flow
            AgentStatus status = agent.Data.currentStatus;
            if (status == AgentStatus.WaitingForApproval || status == AgentStatus.WaitingForInput)
            {
                agent.MoveToManager();
            }
        }

        public TaskData CreateTask(string title, string desc, TaskType type)
        {
            return new TaskData(title, desc, type);
        }
    }
}
